export function createI18n(locale = "zh-CN") {
  let currentLocale = MESSAGES[locale] ? locale : "en";
  return {
    get locale() {
      return currentLocale;
    },
    set locale(value) {
      currentLocale = MESSAGES[value] ? value : "en";
    },
    t(key, params = {}) {
      const template = MESSAGES[currentLocale][key] ?? MESSAGES.en[key] ?? key;
      return Object.entries(params).reduce(
        (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
        template,
      );
    },
    text(value) {
      if (typeof value === "string") return value;
      return value?.[currentLocale] ?? value?.en ?? "";
    },
    number(value, options = {}) {
      return new Intl.NumberFormat(currentLocale, options).format(value);
    }
  };
}
